// Bundles server/*.ts into api/*.js for Vercel. The shared pipeline code uses explicit .ts imports
// (needed by Node's type stripping for local scripts), which Vercel's per-file TypeScript compile
// doesn't rewrite — so the function ships as one pre-bundled file. npm packages stay external;
// Vercel installs them and traces what the bundle needs.
import { defineConfig } from 'rolldown'
import pkg from './package.json' with { type: 'json' }

const external = Object.keys(pkg.dependencies ?? {})

export default defineConfig({
    input: { news: 'server/news.ts' },
    platform: 'node',
    external: id => external.some(dep => id === dep || id.startsWith(`${dep}/`)),
    output: {
        dir: 'api',
        format: 'esm',
        entryFileNames: '[name].js',
        banner: '// GENERATED by `npm run build:api` from server/*.ts — do not edit.',
    },
})
